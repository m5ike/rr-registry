#!/usr/bin/env bash
# make menuconfig - interactive configuration of the RR Registry web backend (.env).
# Uses whiptail or dialog; falls back to plain prompts. Non-interactive: scripts/menuconfig.sh --defaults
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
ENV_FILE="${ENV_FILE:-$ROOT/.env}"

randtok() { LC_ALL=C tr -dc 'A-Za-z0-9' </dev/urandom 2>/dev/null | head -c "${1:-40}" || true; }

# --- defaults, then .env.example, then existing .env
declare -a KEYS=(RR_PORT RR_SSH_PORT RR_BIND RR_PUBLIC_URL RR_ADMIN_USER RR_ADMIN_PASSWORD RR_API_TOKEN RR_DEFAULT_REPO RR_UPSTREAM RR_CACHE_TTL RR_MAX_BODY_MB RR_DATA_PATH RR_CONTAINER RR_UID RR_GID RR_LOG_REQUESTS)
RR_PORT=4873; RR_SSH_PORT=2222; RR_BIND=0.0.0.0; RR_PUBLIC_URL=""; RR_ADMIN_USER=admin; RR_ADMIN_PASSWORD=""; RR_API_TOKEN=""
RR_DEFAULT_REPO=npm; RR_UPSTREAM=https://registry.npmjs.org; RR_CACHE_TTL=300; RR_MAX_BODY_MB=200
RR_DATA_PATH=./data; RR_CONTAINER=rr-registry; RR_UID="$(id -u)"; RR_GID="$(id -g)"; RR_LOG_REQUESTS=1

load() {
  local f="$1" line k v
  [ -f "$f" ] || return 0
  while IFS= read -r line || [ -n "$line" ]; do
    [[ "$line" =~ ^[[:space:]]*([A-Z_][A-Z0-9_]*)=(.*)$ ]] || continue
    k="${BASH_REMATCH[1]}"; v="${BASH_REMATCH[2]}"
    v="${v#\"}"; v="${v%\"}"; v="${v#\'}"; v="${v%\'}"
    printf -v "$k" '%s' "$v"
  done <"$f"
}
load "$ENV_FILE"
[ -z "$RR_ADMIN_PASSWORD" ] || [ "$RR_ADMIN_PASSWORD" = "change-me" ] && RR_ADMIN_PASSWORD="$(randtok 16)"
[ -z "$RR_API_TOKEN" ] || [[ "$RR_API_TOKEN" == change-me* ]] && RR_API_TOKEN="rr_$(randtok 40)"

save() {
  [ -f "$ENV_FILE" ] && cp "$ENV_FILE" "$ENV_FILE.bak"
  umask 077
  {
    echo "# RR Registry configuration - generated by make menuconfig on $(date)"
    for k in "${KEYS[@]}"; do printf '%s=%s\n' "$k" "${!k}"; done
  } >"$ENV_FILE"
  echo "Konfigurace uložena do $ENV_FILE"
  echo "  port:      $RR_PORT"
  echo "  ssh (git): ${RR_SSH_PORT:-vypnuto}"
  echo "  admin:     $RR_ADMIN_USER / (heslo v .env)"
  echo "  api_token: ${RR_API_TOKEN:0:8}…"
  echo "Restartujte server: make restart (Docker) nebo make run (lokálně)."
}

validate() {
  [[ "$RR_PORT" =~ ^[0-9]+$ ]] && [ "$RR_PORT" -ge 1 ] && [ "$RR_PORT" -le 65535 ] || { echo "Neplatný port: $RR_PORT"; return 1; }
  [[ "${RR_SSH_PORT:-0}" =~ ^[0-9]+$ ]] && [ "${RR_SSH_PORT:-0}" -le 65535 ] || { echo "Neplatný SSH port: $RR_SSH_PORT"; return 1; }
  [ "${#RR_ADMIN_PASSWORD}" -ge 4 ] || { echo "Heslo administrátora musí mít aspoň 4 znaky"; return 1; }
  [ "${#RR_API_TOKEN}" -ge 16 ] || { echo "API token musí mít aspoň 16 znaků"; return 1; }
  [[ "$RR_CACHE_TTL" =~ ^[0-9]+$ ]] || { echo "Neplatné TTL"; return 1; }
  return 0
}

if [ "${1:-}" = "--defaults" ]; then
  validate && save
  exit 0
fi

DLG="${DIALOG:-}"
if [ -z "$DLG" ]; then
  if command -v whiptail >/dev/null 2>&1; then DLG=whiptail; elif command -v dialog >/dev/null 2>&1; then DLG=dialog; fi
fi
if [ ! -t 0 ] || [ ! -t 1 ]; then DLG=""; fi

# ------------------------------------------------------------- plain text fallback
if [ -z "$DLG" ]; then
  echo "== RR Registry – konfigurace (Enter = ponechat hodnotu) =="
  ask() { local k="$1" label="$2" v; read -r -p "$label [${!k}]: " v; [ -n "$v" ] && printf -v "$k" '%s' "$v"; return 0; }
  ask RR_PORT "Port web backendu"
  ask RR_SSH_PORT "Port SSH pro git (0 = vypnuto)"
  ask RR_BIND "Adresa pro publikování portu (0.0.0.0 / 127.0.0.1)"
  ask RR_PUBLIC_URL "Veřejná URL (prázdné = automaticky)"
  ask RR_ADMIN_USER "Uživatel administrátora"
  ask RR_ADMIN_PASSWORD "Heslo administrátora"
  ask RR_API_TOKEN "API token"
  ask RR_DEFAULT_REPO "Výchozí repozitář"
  ask RR_UPSTREAM "Upstream registr pro fallback (prázdné = žádný)"
  ask RR_CACHE_TTL "Platnost cache metadat (s)"
  ask RR_DATA_PATH "Adresář s daty (host)"
  validate || exit 1
  save
  exit 0
fi

# ------------------------------------------------------------- whiptail / dialog
ui() { "$DLG" --backtitle "RR Registry – make menuconfig (maintainer m5ike)" "$@" 3>&1 1>&2 2>&3; }
edit() { local k="$1" label="$2" v; v=$(ui --title "$label" --inputbox "$label" 10 74 "${!k}") && printf -v "$k" '%s' "$v"; return 0; }
editpw() { local k="$1" label="$2" v; v=$(ui --title "$label" --passwordbox "$label (prázdné = beze změny)" 10 74) && [ -n "$v" ] && printf -v "$k" '%s' "$v"; return 0; }

while true; do
  choice=$(ui --title "Konfigurace web backendu" --ok-button "Upravit" --cancel-button "Konec" --menu "Vyberte položku (uloží se do .env):" 24 84 15 \
    PORT      "Port web backendu ........... $RR_PORT" \
    SSH       "Port SSH (git) .............. ${RR_SSH_PORT:-0}" \
    BIND      "Publikovat na adrese ........ $RR_BIND" \
    URL       "Veřejná URL ................. ${RR_PUBLIC_URL:-(automaticky)}" \
    ADMIN     "Uživatel administrátora ..... $RR_ADMIN_USER" \
    PASSWORD  "Heslo administrátora ........ ********" \
    TOKEN     "API token ................... ${RR_API_TOKEN:0:10}…" \
    GENTOKEN  "Vygenerovat nový API token" \
    REPO      "Výchozí repozitář ........... $RR_DEFAULT_REPO" \
    UPSTREAM  "Fallback upstream ........... ${RR_UPSTREAM:-(vypnuto)}" \
    TTL       "Platnost cache (s) .......... $RR_CACHE_TTL" \
    BODY      "Max. velikost uploadu (MB) .. $RR_MAX_BODY_MB" \
    DATA      "Adresář dat (host) .......... $RR_DATA_PATH" \
    UIDGID    "UID:GID kontejneru .......... $RR_UID:$RR_GID" \
    SAVE      ">> Uložit a ukončit" \
    QUIT      ">> Ukončit bez uložení") || choice=QUIT
  case "$choice" in
    PORT) edit RR_PORT "Port web backendu (1-65535)" ;;
    SSH) edit RR_SSH_PORT "Port SSH serveru pro git clone/push (1-65535, 0 = vypnuto)" ;;
    BIND) edit RR_BIND "Adresa hostitele pro publikování portu (0.0.0.0 = všude, 127.0.0.1 = jen lokálně)" ;;
    URL) edit RR_PUBLIC_URL "Veřejná URL serveru, např. https://npm.firma.cz (prázdné = z hlavičky Host)" ;;
    ADMIN) edit RR_ADMIN_USER "Uživatelské jméno administrátora" ;;
    PASSWORD) editpw RR_ADMIN_PASSWORD "Nové heslo administrátora" ;;
    TOKEN) edit RR_API_TOKEN "API token (Bearer) s právy administrátora" ;;
    GENTOKEN) RR_API_TOKEN="rr_$(randtok 40)"; ui --title "API token" --msgbox "Nový API token:\n\n$RR_API_TOKEN\n\n(uloží se po volbě Uložit)" 12 74 ;;
    REPO) edit RR_DEFAULT_REPO "Název výchozího npm repozitáře (kořen URL /)" ;;
    UPSTREAM) edit RR_UPSTREAM "Upstream registr pro balíčky, které nejsou lokálně (prázdné = vypnuto; platí při prvním startu)" ;;
    TTL) edit RR_CACHE_TTL "Platnost cache metadat v sekundách" ;;
    BODY) edit RR_MAX_BODY_MB "Maximální velikost požadavku v MB" ;;
    DATA) edit RR_DATA_PATH "Adresář s daty registru na hostiteli (bind mount do /data)" ;;
    UIDGID) edit RR_UID "UID procesu v kontejneru (vlastník adresáře dat)"; edit RR_GID "GID procesu v kontejneru" ;;
    SAVE)
      if msg=$(validate); then clear; save; exit 0; else ui --title "Chyba" --msgbox "$msg" 8 60; fi ;;
    QUIT) clear; echo "Bez uložení."; exit 0 ;;
  esac
done
